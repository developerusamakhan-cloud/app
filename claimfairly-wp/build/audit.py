"""Content audit for ClaimFairly starter content.

For every Markdown page: visible words, FAQ count, internal links out
(in the body) and internal links in (from other pages' bodies and their
"related" lists). Flags pages with fewer than 3 inbound links or with
links that point at pages that do not exist.

Usage (from the claimfairly-wp folder):  python3 build/audit.py
"""
import os
import re
from collections import defaultdict

ROOT = os.path.join(os.path.dirname(__file__), '..', 'claimfairly', 'content')
STATE_PREFIX = 'states/'


def parse(path):
    text = open(path, encoding='utf-8').read()
    head, body = text.split('\n---\n', 1) if text.startswith('---\n') else ('', text)
    meta = dict(re.findall(r'^([a-z_]+):\s*(.*)$', head, re.M))
    related = re.findall(r'^\s+-\s.*\|\s*(/\S*)\s*$', head, re.M)
    return meta, body, related


def visible_words(body):
    b = re.sub(r'\[cf_q q="([^"]*)"\]', r' \1 ', body)
    b = re.sub(r'\[/?cf_[^\]]*\]', ' ', b)
    b = re.sub(r'\]\([^)]*\)', ' ', b)
    b = re.sub(r'[#*|>`\[\]]', ' ', b)
    return len(re.findall(r"[A-Za-z0-9$][A-Za-z0-9$,.%'/-]*", b))


pages = {}
for root, _, files in os.walk(ROOT):
    for name in sorted(files):
        if name.endswith('.md'):
            path = os.path.join(root, name)
            meta, body, related = parse(path)
            key = (meta.get('parent', '') + '/' if meta.get('parent') else '') + meta['slug']
            pages[key] = dict(rel=os.path.relpath(path, ROOT), meta=meta, body=body, related=related)

known = set(pages) | {'', 'home'}
inbound = defaultdict(set)
broken = []
rows = []
for key, p in pages.items():
    body_links = [l.strip('/') for l in re.findall(r'\]\((/[^)#?]*)', p['body'])]
    rel_links = [l.strip('/') for l in p['related']]
    for link in body_links + rel_links:
        if link.startswith(STATE_PREFIX):
            continue  # state pages are generated by the importer
        if link not in known:
            broken.append((p['rel'], '/' + link + '/'))
        elif link != key:
            inbound[link].add(key)
    rows.append((p['rel'], key, visible_words(p['body']), p['body'].count('[cf_q '), len(set(body_links) - {key})))

print(f"{'file':50} {'words':>6} {'faq':>4} {'out':>4} {'in':>4}")
weak = []
for rel, key, words, faq, out in sorted(rows):
    n_in = len(inbound.get(key, ()))
    flag = '' if key in ('home', 'guides') or n_in >= 3 else '  <- fewer than 3 inbound'
    if flag:
        weak.append(rel)
    print(f"{rel:50} {words:6} {faq:4} {out:4} {n_in:4}{flag}")
print()
print('Broken internal links:', broken or 'none')
print('Pages with fewer than 3 inbound links:', weak or 'none')
